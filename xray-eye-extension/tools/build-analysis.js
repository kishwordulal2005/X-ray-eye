#!/usr/bin/env node
/*
 * build-analysis.js — splice src/security-analysis.js into src/engine.js.
 *
 * The analyzer needs the engine's internal stores (response headers, response
 * bodies, JWTs, storage, notes), which the public API only exposes already
 * serialized. Keeping it as a separate source file and splicing it in keeps the
 * detector readable instead of burying it in a 10k-line IIFE, while the shipped
 * extension still ships one self-contained engine file.
 *
 *   node tools/build-analysis.js          check that engine.js is in sync
 *   node tools/build-analysis.js --write  splice and update engine.js
 *
 * The check mode is what CI and the test suite use, so an edit to the module
 * that was never built cannot ship.
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const MODULE = path.join(ROOT, "src", "security-analysis.js");
const ENGINE = path.join(ROOT, "src", "engine.js");

const START = "// >>> security-analysis (generated by tools/build-analysis.js)";
const END = "// <<< security-analysis";

// The block is written as START...END with NO trailing newline, and joined to
// the surrounding file with exactly one blank line. The strip pattern below
// then removes the same span, so a build is idempotent. An earlier version put
// the newline on the join instead and every build grew the file by one byte -
// which read as "out of sync" forever after, because the file could never be
// reproduced by running the build again.
function build() {
  const moduleSrc = fs.readFileSync(MODULE, "utf8").replace(/\r\n/g, "\n");
  return (
    START + "\n" +
    "  // Generated block. Edit src/security-analysis.js, then run\n" +
    "  // `node tools/build-analysis.js --write`. Do not edit in place.\n" +
    moduleSrc.replace(/\s+$/, "") + "\n" +
    END
  );
}

function stripBlock(engineSrc) {
  const re = new RegExp(
    "^[ \\t]*" + esc(START) + "\\n[\\s\\S]*?^[ \\t]*" + esc(END) + "\\n\\n",
    "m"
  );
  const out = engineSrc.replace(re, "");
  if (out === engineSrc) throw new Error("marker not found in engine.js - is engine.js corrupt?");
  return out;
}

function esc(s) { return String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

function main() {
  const write = process.argv.includes("--write");
  const engineSrc = fs.readFileSync(ENGINE, "utf8").replace(/\r\n/g, "\n");

  // Always rebuild from a stripped engine so re-running the script is
  // idempotent instead of stacking copies of the block.
  const base = engineSrc.includes(START) ? stripBlock(engineSrc) : engineSrc;
  const anchor = "  // =====================================================================\n  // Body and header description";
  const at = base.indexOf(anchor);
  if (at < 0) {
    throw new Error("anchor not found in engine.js - is engine.js corrupt?");
  }

  const next = base.slice(0, at) + build() + "\n\n" + base.slice(at);

  if (!write) {
    if (next === engineSrc) {
      console.log("security-analysis: in sync");
      process.exit(0);
    }
    console.error("security-analysis: OUT OF SYNC - engine.js does not match src/security-analysis.js");
    console.error("run: node tools/build-analysis.js --write");
    process.exit(1);
  }

  // CRLF matches the rest of the file so the diff stays readable on Windows.
  const eol = fs.readFileSync(ENGINE, "utf8").includes("\r\n") ? "\r\n" : "\n";
  fs.writeFileSync(ENGINE, next.replace(/\n/g, eol), "utf8");
  console.log("security-analysis: spliced into src/engine.js (" +
    moduleSrcLines() + " lines from src/security-analysis.js)");
}

function moduleSrcLines() {
  return fs.readFileSync(MODULE, "utf8").replace(/\r\n/g, "\n").split("\n").length;
}

main();